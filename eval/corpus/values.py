"""Synthetic identifiers for the corpus, and the hard negatives that sit beside them.

Every checksummed value here comes from the generators in `scripts/make-pii-fixture.py`,
loaded rather than reimplemented. That file's Verhoeff, Luhn and GSTIN implementations
are independent of the TypeScript validators on purpose -- a fixture generated by the
code under test proves only that the code agrees with itself -- and a third copy in this
file would throw that property away.

Nothing here is real. Every Aadhaar, PAN, card and account number is generated to pass
its checksum and to belong to nobody; every name, address and email is invented. That is
a hard requirement rather than a courtesy: a corpus is committed to the repository, and
a screenshot of one ends up enlarged on a slide.
"""

from __future__ import annotations

import importlib.util
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# -- The checksum generators, borrowed rather than copied ----------------------


def _load_fixture_module():
    path = ROOT / "scripts" / "make-pii-fixture.py"
    spec = importlib.util.spec_from_file_location("sih_pii_fixture", path)
    if spec is None or spec.loader is None:  # pragma: no cover
        raise ImportError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules["sih_pii_fixture"] = module
    spec.loader.exec_module(module)
    return module


_fx = _load_fixture_module()

verhoeff_ok = _fx.verhoeff_ok
verhoeff_check_digit = _fx.verhoeff_check_digit
luhn_ok = _fx.luhn_ok
make_aadhaar = _fx.make_aadhaar
make_card = _fx.make_card
make_pan = _fx.make_pan
make_gstin = _fx.make_gstin

# -- Invented people -----------------------------------------------------------

FIRST = [
    "Asha", "Ravi", "Meera", "Arjun", "Kavya", "Nikhil", "Priya", "Rohan",
    "Divya", "Sanjay", "Lakshmi", "Imran", "Neha", "Vikram", "Anita", "Farhan",
    "Sneha", "Aditya", "Rekha", "Manish", "Pooja", "Deepak", "Ananya", "Suresh",
]
LAST = [
    "Menon", "Kulkarni", "Iyer", "Sharma", "Reddy", "Banerjee", "Nair", "Patil",
    "Chatterjee", "Desai", "Rao", "Khan", "Joshi", "Pillai", "Bhattacharya",
    "Gowda", "Verma", "Sundaram", "Mishra", "Fernandes",
]

STREETS = [
    "4th Cross, Jayanagar", "Sector 12, Dwarka", "MG Road", "Anna Salai",
    "Park Street", "Banjara Hills Road No. 3", "SV Road, Andheri West",
    "Civil Lines", "Ashok Nagar", "Salt Lake Sector V",
]
CITIES = [
    ("Bengaluru", "Karnataka", "560041"),
    ("New Delhi", "Delhi", "110075"),
    ("Chennai", "Tamil Nadu", "600002"),
    ("Kolkata", "West Bengal", "700016"),
    ("Hyderabad", "Telangana", "500034"),
    ("Mumbai", "Maharashtra", "400058"),
    ("Pune", "Maharashtra", "411001"),
    ("Kochi", "Kerala", "682016"),
]

BANKS = ["HDFC", "SBIN", "ICIC", "PUNB", "UTIB", "KKBK", "CNRB", "BARB"]
UPI_HANDLES = ["okhdfcbank", "oksbi", "ybl", "paytm", "apl", "ibl"]


class Values:
    """A deterministic source of invented identifiers, one instance per corpus build."""

    def __init__(self, seed: int) -> None:
        self.rng = random.Random(seed)

    # -- people ---------------------------------------------------------------
    def person(self) -> str:
        return f"{self.rng.choice(FIRST)} {self.rng.choice(LAST)}"

    def address(self) -> str:
        city, state, pin = self.rng.choice(CITIES)
        door = self.rng.randint(1, 240)
        return f"{door}, {self.rng.choice(STREETS)}, {city}, {state} {pin}"

    def address_lines(self) -> list[str]:
        city, state, pin = self.rng.choice(CITIES)
        return [
            f"{self.rng.randint(1, 240)}, {self.rng.choice(STREETS)}",
            f"{city}, {state}",
            pin,
        ]

    def email(self, name: str | None = None) -> str:
        name = name or self.person()
        parts = name.lower().split()
        domain = self.rng.choice(["example.in", "example.com", "mail.example.org"])
        return f"{parts[0]}.{parts[-1]}@{domain}"

    def phone(self) -> str:
        n = f"{self.rng.randint(6, 9)}{self.rng.randint(0, 10 ** 9 - 1):09d}"
        style = self.rng.randint(0, 2)
        if style == 0:
            return n
        if style == 1:
            return f"+91 {n[:5]} {n[5:]}"
        return f"0{n[:4]} {n[4:]}"

    def dob(self) -> str:
        d = self.rng.randint(1, 28)
        m = self.rng.randint(1, 12)
        y = self.rng.randint(1960, 2004)
        return f"{d:02d}/{m:02d}/{y}"

    # -- identifiers ----------------------------------------------------------
    def aadhaar(self, spaced: bool = True) -> str:
        n = make_aadhaar(self.rng)
        return f"{n[:4]} {n[4:8]} {n[8:]}" if spaced else n

    def pan(self, entity: str = "P") -> str:
        return make_pan(self.rng, entity)

    def gstin(self) -> str:
        return make_gstin(self.rng)

    def ifsc(self) -> str:
        return f"{self.rng.choice(BANKS)}0{self.rng.randint(100000, 999999)}"

    def upi(self) -> str:
        first = self.rng.choice(FIRST).lower()
        last = self.rng.choice(LAST).lower()
        return f"{first}.{last}@{self.rng.choice(UPI_HANDLES)}"

    def account(self) -> str:
        width = self.rng.choice([11, 14, 16])
        return "".join(str(self.rng.randint(0, 9)) for _ in range(width))

    def card(self) -> str:
        prefix = self.rng.choice(["4", "51", "52", "34", "6521"])
        length = 15 if prefix == "34" else 16
        n = make_card(prefix, length, self.rng)
        return " ".join(n[i:i + 4] for i in range(0, len(n), 4))

    def passport(self) -> str:
        return f"{self.rng.choice('JKLMNPRSTUVWXYZ')}{self.rng.randint(1000000, 9999999)}"

    def licence(self) -> str:
        state = self.rng.choice(["KA", "MH", "TN", "DL", "WB", "TS", "KL"])
        rto = self.rng.randint(1, 70)
        year = self.rng.randint(1990, 2020)
        serial = self.rng.randint(1000000, 9999999)
        return f"{state}{rto:02d} {year}{serial}"

    def secret(self) -> str:
        return "".join(self.rng.choice("abcdefghjkmnpqrstuvwxyz23456789") for _ in range(10))

    def org(self) -> str:
        return self.rng.choice(
            [
                "Kaveri Textiles Pvt Ltd", "Nandi Logistics", "Sahyadri Foods",
                "Deccan Instruments", "Bharat Micro Systems", "Konkan Traders",
            ]
        )


# -- Hard negatives ------------------------------------------------------------
#
# Sixty of these across the corpus is the requirement, and they are the half that proves
# precision rather than asserting it. Each carries the reason it is a trap, so a false
# positive in the report says *which* trap the detector fell into rather than merely
# that it fell into one.
#
# The Verhoeff-valid ones matter most. Roughly one random twelve-digit string in ten
# passes Verhoeff by chance, so an invoice number really can satisfy the arithmetic and
# the only thing separating it from an Aadhaar is the label beside it. A detector that
# reaches for the checksum and stops there has already failed this corpus.


def hard_negatives(rng: random.Random) -> list[dict]:
    """Traps, each shaped exactly like something in the vocabulary and none of it PII."""
    out: list[dict] = []

    def add(text: str, why: str, looks_like: str) -> None:
        out.append({"text": text, "why": why, "looksLike": looks_like})

    # Twelve digits that pass Verhoeff, labelled as anything but an Aadhaar.
    for label in [
        "Invoice no.", "Order ID", "Reference", "Txn", "Challan", "Waybill",
        "Consignment", "Docket", "Ticket", "Requisition",
    ]:
        body = str(rng.randint(2, 9)) + "".join(str(rng.randint(0, 9)) for _ in range(10))
        digits = body + str(verhoeff_check_digit(body))
        add(f"{label} {digits}", f"verhoeff-valid but labelled {label.lower()}", "AADHAAR")

    # Twelve digits that do not even pass, which must be rejected twice over.
    for label in ["Bill no.", "Receipt", "Case ID", "File no.", "Batch"]:
        digits = "".join(str(rng.randint(0, 9)) for _ in range(12))
        if verhoeff_ok(digits):
            digits = digits[:-1] + str((int(digits[-1]) + 1) % 10)
        add(f"{label} {digits}", "twelve digits, wrong checksum, wrong label", "AADHAAR")

    # Sixteen-digit reference codes: card-shaped and Luhn-invalid, then card-shaped and
    # Luhn-*valid*. The second kind is what catches a detector that stops at Luhn.
    for label in ["Ref", "Tracking", "UTR", "Shipment", "Policy ref"]:
        digits = "".join(str(rng.randint(0, 9)) for _ in range(16))
        if luhn_ok(digits):
            digits = digits[:-1] + str((int(digits[-1]) + 1) % 10)
        grouped = " ".join(digits[i:i + 4] for i in range(0, 16, 4))
        add(f"{label} {grouped}", "sixteen digits, fails Luhn, labelled a reference", "CARD")
    for label in ["UTR", "Shipment"]:
        n = make_card("9", 16, rng)
        grouped = " ".join(n[i:i + 4] for i in range(0, 16, 4))
        add(f"{label} {grouped}", "sixteen digits, Luhn-valid, 9-prefix no issuer uses", "CARD")

    # Currency whose grouping mimics a card number once the separators are ignored.
    for amount in ["4,532 1290 4471", "5,100 2233 8890", "3,415 9000 1122"]:
        add(f"Rs {amount}", "a rupee amount whose grouping mimics a 16-digit card", "CARD")

    # Dates that are not birthdays.
    for label, date in [
        ("Issued on", "12/03/2021"), ("Valid till", "31/12/2027"),
        ("Filed on", "04/07/2023"), ("Due date", "15/09/2024"),
        ("Last updated", "28/02/2025"), ("Meeting", "09/11/2026"),
        ("Renewal", "01/04/2028"), ("Statement period", "01/06/2024"),
    ]:
        add(f"{label} {date}", "a date with no birth context", "DOB")

    # Place names that are also person names, and the other way round.
    for place in [
        "Nagpur", "Salem", "Georgia", "Jordan", "Florence", "Austin",
        "Madison", "Victoria", "Chelsea", "Preston",
    ]:
        add(place, "a place name that is also a common given or family name", "PERSON")

    # PAN-shaped strings that are not PANs.
    for code, why in [
        ("ABCDX1234Z", "PAN shape with an entity code that does not exist"),
        ("TESTP0000A", "PAN shape, a placeholder in the site's own help text"),
        ("FORMP1234X", "PAN shape appearing inside the word FORM in a heading"),
    ]:
        add(code, why, "PAN")

    # IFSC-shaped and GSTIN-shaped strings.
    add("HDFC0XXXXXX", "IFSC shape, branch masked by the site itself", "IFSC")
    add("SBIN0000000", "IFSC shape, the all-zero example from the bank's help page", "IFSC")
    add(
        "29AAAAA0000A1Z5",
        "the GSTIN the government's own documentation uses as an example",
        "GSTIN",
    )

    # Phone-shaped things that are not phones.
    for text, why in [
        ("PIN 560041", "a postal code, six digits"),
        ("1800 200 3333", "a toll-free helpline, not a personal number"),
        ("139", "a railway helpline short code"),
        ("Bill amount 9845012345", "ten digits that happen to be an amount in paise"),
    ]:
        add(text, why, "PHONE")

    # Email-shaped strings that belong to nobody.
    for text, why in [
        ("support@example.in", "a support desk, not a person"),
        ("noreply@example.in", "an unattended mailbox"),
        ("name@company.com", "the placeholder in the field's own hint text"),
    ]:
        add(text, why, "EMAIL")

    # UPI-shaped handles that address a business, not a person.
    for text, why in [
        ("bescom.bill@okaxis", "a utility's collection handle, printed on every bill"),
        ("merchant0042@ybl", "a merchant terminal id, the same for every customer"),
    ]:
        add(text, why, "UPI")

    # Account-shaped digit runs that identify an institution, not a customer.
    for text, why in [
        ("Branch code 00042317", "a branch code, the same for everyone who banks there"),
        ("MICR 560240021", "an MICR code, a property of the branch"),
        ("Consumer no. 3407120054", "a metering point, printed on a public bill"),
    ]:
        add(text, why, "ACCOUNT")

    # Passport- and licence-shaped strings from the forms' own instructions.
    for text, why, cls in [
        ("A1234567", "the passport format example in the form's help text", "PASSPORT"),
        ("Form no. Z9876543", "a form serial that happens to match the passport shape", "PASSPORT"),
        ("KA00 00000000000", "the licence format example on the RTO's own page", "LICENCE"),
    ]:
        add(text, why, cls)

    return out
